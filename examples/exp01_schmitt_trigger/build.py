def fm(s, **kw):
    """Fill «name» slots (LaTeX keeps its own braces untouched)."""
    for k, v in kw.items():
        s = s.replace('«' + k + '»', str(v))
    if '«' in s or '»' in s:                       # never print an unfilled slot into a report
        raise ValueError(f'unfilled slot in: {s[:80]}')
    return s


def g(x, d=2):
    return f'{x:.{d}f}'


